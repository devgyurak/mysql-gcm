#!/usr/bin/env bash
# Starts (or reuses) a local MySQL container for one major version. Port 0 lets the
# daemon pick a free host port, so several versions run side by side.
#
#   scripts/dev-up.sh 8.4
set -euo pipefail

usage() {
  echo "usage: $(basename "$0") <mysql-major>   e.g. 8.0 | 8.4 | 9" >&2
  exit 2
}
[ $# -eq 1 ] || usage
ver="$1"

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# GCM_DEV_NAME renames the container. scripts/verify-nested.sh uses it to get the
# keyring setup below on a throwaway container without touching the development
# server; the default is the name it has always had.
name="${GCM_DEV_NAME:-mysql-dev-${ver}}"

image="$(
  python3 - "${root}/docker/versions.json" "${ver}" <<'PY'
import json, sys

path, major = sys.argv[1], sys.argv[2]
with open(path, encoding="utf-8") as fh:
    versions = json.load(fh)
if major not in versions:
    sys.exit(f"unknown MySQL major {major!r}; known: {', '.join(versions)}")
print(versions[major]["image"])
PY
)"

if ! docker inspect "${name}" >/dev/null 2>&1; then
  # binlog_format was removed in MySQL 9.0 (ROW is the only format there); passing
  # it would stop the server from starting.
  server_args=(--loose_gcm.strict=ON --general_log=OFF)
  case "${ver}" in
    9*) : ;;
    *) server_args+=(--binlog_format=ROW) ;;
  esac

  # general_log=OFF even in development: keys and plaintext travel as SQL
  # arguments, so the log would hold them (docs/design.md §6).
  # The healthcheck goes over TCP on purpose. While the official image initialises a
  # fresh data directory it starts a *temporary* server that listens on the socket only
  # (the log says `port: 0`), and `mysqladmin ping` over the socket answers from that
  # one — so a socket healthcheck reports healthy, the caller installs the component,
  # and moments later the entrypoint stops that server and starts the real one, losing
  # everything. Requiring a TCP connection excludes the temporary server by
  # construction. This only shows up on a first initialisation, which is why it passed
  # locally on reused containers and failed on a fresh CI runner.
  docker run -d --name "${name}" \
    -e MYSQL_ALLOW_EMPTY_PASSWORD=1 \
    -p 0:3306 \
    --health-cmd='mysqladmin ping -h 127.0.0.1 -P 3306 -uroot --silent' \
    --health-interval=2s \
    --health-retries=30 \
    "${image}" "${server_args[@]}" >/dev/null
fi

docker start "${name}" >/dev/null 2>&1 || true

wait_ready() {
  local deadline=$((SECONDS + 300))
  while [ "$(docker inspect -f '{{.State.Health.Status}}' "${name}")" != healthy ]; do
    if [ "${SECONDS}" -ge "${deadline}" ]; then
      echo "${name} did not become healthy within 300s; last log lines:" >&2
      docker logs --tail 40 "${name}" >&2
      exit 1
    fi
    sleep 2
  done

  # Belt and braces: the healthcheck says the server answers, this says it answers *us*
  # and has finished starting. A fresh container that is still running init scripts can
  # accept a connection and still reject a query.
  local probe_deadline=$((SECONDS + 120))
  until docker exec "${name}" mysql -uroot -N -e 'SELECT 1' >/dev/null 2>&1; do
    if [ "${SECONDS}" -ge "${probe_deadline}" ]; then
      echo "${name} is healthy but not answering queries; last log lines:" >&2
      docker logs --tail 40 "${name}" >&2
      exit 1
    fi
    sleep 1
  done
}
wait_ready

# The file keyring and the server's general-purpose keyring functions, for the cases
# that read a key by id (docs/design.md amendment A13). Development and test only: the
# key file sits beside the data, which is exactly what design §3 rules out for
# production. Nothing here is committed key material — the files are written inside the
# container and the keys are generated by the cases that use them.
#
# A keyring component loads from a manifest next to the mysqld binary, before any SQL
# can run, so this is files plus a restart rather than a statement. It is applied to a
# reused container too, which is what lets one created before this existed keep working.
dev_mysql() { docker exec "${name}" mysql -uroot -N "$@"; }
keyring_active() {
  [ "$(dev_mysql -e "SELECT STATUS_VALUE FROM performance_schema.keyring_component_status
                     WHERE STATUS_KEY = 'Component_status'" 2>/dev/null)" = Active ]
}
if ! keyring_active; then
  plugin_dir="$(dev_mysql -e 'SELECT @@plugin_dir' | tr -d '\r')"
  # The data file is created here, owned by mysql, on purpose. The image's entrypoint
  # runs `mysqld --verbose --help` as root before it drops privileges, the component
  # creates a missing file during that run, and the server proper then cannot read a
  # root-owned file: the component stays loaded and reports itself Disabled.
  docker exec -e GCM_PLUGIN_DIR="${plugin_dir}" "${name}" sh -c '
    set -e
    bin_dir="$(dirname "$(readlink -f "$(command -v mysqld)")")"
    data_dir=/var/lib/mysql-keyring
    mkdir -p "${data_dir}"
    touch "${data_dir}/component_keyring_file"
    chown -R mysql:mysql "${data_dir}"
    printf "{\"components\": \"file://component_keyring_file\"}\n" > "${bin_dir}/mysqld.my"
    printf "{\"path\": \"%s/component_keyring_file\", \"read_only\": false}\n" "${data_dir}" \
      > "${GCM_PLUGIN_DIR}/component_keyring_file.cnf"
  '
  docker restart "${name}" >/dev/null
  wait_ready
  keyring_active || {
    echo "${name}: component_keyring_file did not become Active; last log lines:" >&2
    docker logs --tail 40 "${name}" >&2
    exit 1
  }
fi

# keyring_udf is how a test creates a key without ever putting key bytes in a statement
# (keyring_key_generate). Checked rather than assumed, so a rerun is a no-op.
if [ "$(dev_mysql -e "SELECT COUNT(*) FROM information_schema.plugins
                      WHERE PLUGIN_NAME = 'keyring_udf'")" = 0 ]; then
  dev_mysql -e "INSTALL PLUGIN keyring_udf SONAME 'keyring_udf.so'"
fi
for fn in keyring_key_generate:INTEGER keyring_key_store:INTEGER keyring_key_remove:INTEGER \
  keyring_key_fetch:STRING keyring_key_type_fetch:STRING keyring_key_length_fetch:INTEGER; do
  if [ "$(dev_mysql -e "SELECT COUNT(*) FROM mysql.func WHERE name = '${fn%%:*}'")" = 0 ]; then
    dev_mysql -e "CREATE FUNCTION ${fn%%:*} RETURNS ${fn##*:} SONAME 'keyring_udf.so'"
  fi
done

port="$(docker port "${name}" 3306/tcp | head -1 | cut -d: -f2)"
echo "${name} ready on host port ${port}"
